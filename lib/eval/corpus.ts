import 'server-only';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { type RiskClass } from '@/lib/extraction/fields';
import { CORPUS_ROOT, itemsIn } from '@/lib/eval/manifest';

/**
 * The G9 corpus loader — the DEVELOPMENT half (slice-5 plan B1; Q5 SETTLED;
 * TSD §6.10; PRD §6.4, Appendix B).
 *
 * ONE governed corpus, TWO consumers, IMMUTABLE PARTITIONS. This module is
 * the development partition's only door: the worker and adapter tests, the
 * fixture server, and prompt/schema iteration all read HERE. The BLIND
 * partition lives behind `lib/eval/blind.ts`, which the §1.7 import fence
 * restricts to the scored eval harness — so the bands G9 signs are never
 * measured on the set they were developed against.
 *
 * Everything under `fixtures/g9` is SYNTHETIC, generated byte-for-byte by
 * `scripts/fixtures/g9-build.mjs` from a spec table in that script. Never a
 * real family's material, at any stage. `readCorpusFile` re-hashes on every
 * read, so a fixture that drifts from its manifest entry is a loud failure
 * rather than a quietly different corpus.
 */

export type CorpusPartition = 'development' | 'blind';

export type SourceType = 'born_digital_pdf' | 'scanned_pdf' | 'photo_jpeg' | 'email_text';

/** What the pipeline is expected to do with the item — the honest-limits
 *  fixtures (§4.3 normalize, §6.8) are part of the same governed corpus. */
export type ExpectedOutcome =
  | 'extracted'
  | 'needs_password'
  | 'unsupported_type'
  | 'refused'
  | 'aborted';

export type CorpusLabel = {
  field: string;
  value: string;
  risk_class: RiskClass;
  /** 1-indexed, matching §6.4's `{page, bbox}` citation geometry. */
  page: number;
  /** [x, y, w, h] in normalised page coordinates (0–1), against the page
   *  AS DISPLAYED — EXIF orientation already applied. */
  bbox: [number, number, number, number];
};

export type AmbiguousLabel = {
  field: string;
  candidates: string[];
  adjudicated: string;
  rationale: string;
};

export type CorpusItem = {
  id: string;
  partition: CorpusPartition;
  document_class: string;
  source_type: SourceType;
  /** The hc.doc_category the drafted document proposal should carry, or
   *  null for items that never reach a proposal. */
  category: string | null;
  expected_outcome: ExpectedOutcome;
  /** Repo-relative to CORPUS_ROOT, always `<partition>/<file>`. */
  file: string;
  bytes: number;
  sha256: string;
  labels: CorpusLabel[];
  /** Banded fields this item genuinely does NOT carry — the negative
   *  examples recall is measured against. */
  absent_fields: string[];
  ambiguous?: AmbiguousLabel[];
  expects_anomaly_flags?: string[];
  notes: string;
};

export type CorpusManifest = {
  version: number;
  built_by: string;
  spec: string;
  band_fields: string[];
  minimums: {
    blind_support_per_field: number;
    source_types_per_field: number;
    blind_negatives_per_field: number;
    ambiguous_per_partition: number;
  };
  items: CorpusItem[];
};


/**
 * The development partition: worker/adapter tests, the fixture server,
 * prompt and schema iteration. Never the scored set.
 */
export function developmentCorpus(): CorpusItem[] {
  return itemsIn('development');
}

/**
 * One DEVELOPMENT item by id.
 *
 * Deliberately scoped to the development partition (round-16 R6/F-2): the
 * old form searched the whole manifest, so `corpusItem('blind-eob-01')` was
 * a supported way to hold a scored item from anywhere in the tree. A blind
 * item is reached through `lib/eval/blind.ts` or not at all.
 */
export function corpusItem(id: string): CorpusItem {
  const item = developmentCorpus().find((i) => i.id === id);
  if (!item) throw new Error(`g9 corpus: no development item ${id}`);
  return item;
}

/** Read one item's bytes, re-hashing against the manifest. A fixture that
 *  no longer matches its recorded digest is a corpus defect, not an input. */
export function readCorpusFile(item: CorpusItem): Uint8Array {
  const bytes = readFileSync(path.join(CORPUS_ROOT, item.file));
  const sha = createHash('sha256').update(bytes).digest('hex');
  if (sha !== item.sha256) {
    throw new Error(`g9 corpus: ${item.id} hashes ${sha}, manifest says ${item.sha256}`);
  }
  if (bytes.byteLength !== item.bytes) {
    throw new Error(`g9 corpus: ${item.id} is ${bytes.byteLength} bytes, manifest says ${item.bytes}`);
  }
  return new Uint8Array(bytes);
}

/** The mime type a corpus item's bytes actually are — stated by the
 *  builder's extension, and cross-checked by sniffMime at the call sites
 *  that care (§4.6: content, never declaration). */
export function corpusMime(item: CorpusItem): string {
  if (item.file.endsWith('.pdf')) return 'application/pdf';
  if (item.file.endsWith('.jpg')) return 'image/jpeg';
  if (item.file.endsWith('.txt')) return 'text/plain';
  return 'application/octet-stream';
}
