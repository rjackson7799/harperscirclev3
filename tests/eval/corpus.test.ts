describe('B1 · labels are well-formed and agree with the field catalogue', () => {
  it('every labelled field is catalogued, and its risk_class is the catalogue answer', () => {
    for (const item of all) {
      for (const label of item.labels) {
        expect(isKnownField(label.field), `${item.id}:${label.field} catalogued`).toBe(true);
        expect(label.risk_class, `${item.id}:${label.field} risk`).toBe(
          riskClassFor(label.field, label.value),
        );
      }
    }
  });

  it('every citation is a real region of a real page (§6.4 normalised geometry)', () => {
    for (const item of all) {
      for (const label of item.labels) {
        expect(label.page, `${item.id}:${label.field} page`).toBeGreaterThanOrEqual(1);
        const [x, y, w, h] = label.bbox;
        for (const n of [x, y, w, h]) expect(Number.isFinite(n)).toBe(true);
        expect(x).toBeGreaterThanOrEqual(0);
        expect(y).toBeGreaterThanOrEqual(0);
        expect(w).toBeGreaterThan(0);
        expect(h).toBeGreaterThan(0);
        expect(x + w, `${item.id}:${label.field} right edge`).toBeLessThanOrEqual(1);
        expect(y + h, `${item.id}:${label.field} bottom edge`).toBeLessThanOrEqual(1);
      }
    }
  });

  it('a field is never both labelled present and declared absent on the same item', () => {
    for (const item of all) {
      const labelled = new Set(item.labels.map((l) => l.field));
      for (const absent of item.absent_fields) {
        expect(labelled.has(absent), `${item.id}: ${absent} cannot be both`).toBe(false);
        expect(isKnownField(absent)).toBe(true);
      }
    }
  });

  it('an item that is not expected to extract carries no labels', () => {
    for (const item of all) {
      if (item.expected_outcome !== 'extracted') expect(item.labels).toEqual([]);
    }
  });
});

describe('B1 · the corpus spec is MEASURED, not merely written down', () => {
  const { minimums } = manifest;

  // AMENDED at the round-16 sign-off. This block was titled "is MET" and the
  // leg below "clears the stated blind support"; both were true of the LABELS
  // and false of the MATERIAL (ADR-0023 D11, spec §4.2). The assertions are
  // unchanged and still worth keeping — they are what a grown corpus has to
  // reach — but they are now named for what they actually measure.
  it('every banded field clears the stated LABELLED blind support', () => {
    for (const field of manifest.band_fields) {
      const supporting = blind.filter((i) => i.labels.some((l) => l.field === field));
      expect(supporting.length, `blind support for ${field}`).toBeGreaterThanOrEqual(
        minimums.blind_support_per_field,
      );
      const sourceTypes = new Set(supporting.map((i) => i.source_type));
      expect(sourceTypes.size, `source types for ${field}`).toBeGreaterThanOrEqual(
        minimums.source_types_per_field,
      );
    }
  });

  it('every banded field has negative examples — a field genuinely absent', () => {
    for (const field of manifest.band_fields) {
      const negatives = blind.filter((i) => i.absent_fields.includes(field));
      expect(negatives.length, `blind negatives for ${field}`).toBeGreaterThanOrEqual(
        minimums.blind_negatives_per_field,
      );
    }
  });

  it('each partition carries adjudicated ambiguous labels', () => {
    for (const [name, items] of [
      ['development', dev],
      ['blind', blind],
    ] as const) {
      const ambiguous = items.flatMap((i) => i.ambiguous ?? []);
      expect(ambiguous.length, `${name} ambiguous labels`).toBeGreaterThanOrEqual(
        minimums.ambiguous_per_partition,
      );
      for (const a of ambiguous) {
        expect(a.candidates.length).toBeGreaterThanOrEqual(2);
        expect(a.candidates).toContain(a.adjudicated);
        expect(a.rationale.length).toBeGreaterThan(0);
      }
    }
  });

  it('the document classes PRD §6.4 names are all present', () => {
    const classes = new Set(all.map((i) => i.document_class));
    for (const required of [
      'discharge_summary',
      'eob',
      'pill_bottle',
      'handwritten_note',
      'phone_photo_angled',
    ]) {
      expect(classes.has(required), `${required} present`).toBe(true);
    }
  });

  it('the development partition carries the honest-limits fixtures the pipeline must survive', () => {
    const outcomes = new Set(dev.map((i) => i.expected_outcome));
    for (const required of ['needs_password', 'unsupported_type', 'aborted'] as const) {
      expect(outcomes.has(required), `${required} fixture present`).toBe(true);
    }
    // The injection probe is B5's INJ-01 fixture; it EXTRACTS — the whole
    // point is that a fully successful injection still lands as a proposal.
    expect(dev.some((i) => i.document_class === 'injection_probe')).toBe(true);
  });
});

