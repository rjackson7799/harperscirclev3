const manifest = corpusManifest();
const dev = developmentCorpus();
const blind = blindCorpus();
const all: CorpusItem[] = [...dev, ...blind];

function sha256(bytes: Uint8Array): string {
  return createHash('sha256').update(bytes).digest('hex');
}

function walk(dir: string, acc: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, acc);
    else acc.push(full);
  }
  return acc;
}

describe('B1 · the manifest is the corpus — nothing rides along unlabelled', () => {
  it('every manifest item resolves to a file whose bytes hash as recorded', () => {
    expect(all.length).toBeGreaterThan(0);
    for (const item of all) {
      const bytes = readCorpusFile(item);
      expect(bytes.byteLength, `${item.id} byte count`).toBe(item.bytes);
      expect(sha256(bytes), `${item.id} sha256`).toBe(item.sha256);
    }
  });

  it('every file under fixtures/g9 is a manifest item — no second fixture world', () => {
    const onDisk = walk(CORPUS_ROOT)
      .map((p) => path.relative(CORPUS_ROOT, p).split(path.sep).join('/'))
      .filter((p) => p !== 'corpus.json');
    const claimed = new Set(all.map((i) => i.file));
    for (const file of onDisk) expect(claimed.has(file), `${file} is in the manifest`).toBe(true);
    expect(onDisk.length).toBe(claimed.size);
  });

  it('ids are unique and files are never shared across items', () => {
    expect(new Set(all.map((i) => i.id)).size).toBe(all.length);
    expect(new Set(all.map((i) => i.file)).size).toBe(all.length);
  });
});

