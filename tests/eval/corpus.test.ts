import { describe, expect, it } from 'vitest';
import { createHash } from 'node:crypto';
import { readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { CORPUS_ROOT, corpusManifest } from '@/lib/eval/manifest';
import { developmentCorpus, readCorpusFile, type CorpusItem } from '@/lib/eval/corpus';
import { blindCorpus } from '@/lib/eval/blind';
import { isKnownField, riskClassFor } from '@/lib/extraction/fields';

// ============================================================================
// B1 · The G9 corpus (slice-5 plan B1, Q5 SETTLED; TSD §6.10; PRD §6.4,
// Appendix B). ONE governed corpus, TWO consumers, IMMUTABLE PARTITIONS:
//
//   development — worker/adapter tests, the fixture server, prompt and
//                 schema iteration. Reachable from lib/eval/corpus.
//   BLIND       — scored eval runs ONLY, so the reported bands are never
//                 measured on their own development set. Reachable only
//                 from lib/eval/blind, which the ESLint fence restricts to
//                 the harness (tests/lint/db-fence.test.ts pins it).
//
// Everything here is SYNTHETIC by construction — generated byte-for-byte by
// scripts/fixtures/g9-build.mjs from a spec table in that script. Never a
// real family's material, at any stage.
// ============================================================================

const manifest = corpusManifest();
const dev = developmentCorpus();
const blind = blindCorpus();
const all: CorpusItem[] = [...dev, ...blind];

function sha256(bytes: Uint8Array): string {
  return createHash('sha256').update(bytes).digest('hex');
}

function walk(dir: string, acc: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, acc);
    else acc.push(full);
  }
  return acc;
}

describe('B1 · the manifest is the corpus — nothing rides along unlabelled', () => {
  it('every manifest item resolves to a file whose bytes hash as recorded', () => {
    expect(all.length).toBeGreaterThan(0);
    for (const item of all) {
      const bytes = readCorpusFile(item);
      expect(bytes.byteLength, `${item.id} byte count`).toBe(item.bytes);
      expect(sha256(bytes), `${item.id} sha256`).toBe(item.sha256);
    }
  });

  it('every file under fixtures/g9 is a manifest item — no second fixture world', () => {
    const onDisk = walk(CORPUS_ROOT)
      .map((p) => path.relative(CORPUS_ROOT, p).split(path.sep).join('/'))
      .filter((p) => p !== 'corpus.json');
    const claimed = new Set(all.map((i) => i.file));
    for (const file of onDisk) expect(claimed.has(file), `${file} is in the manifest`).toBe(true);
    expect(onDisk.length).toBe(claimed.size);
  });

  it('ids are unique and files are never shared across items', () => {
    expect(new Set(all.map((i) => i.id)).size).toBe(all.length);
    expect(new Set(all.map((i) => i.file)).size).toBe(all.length);
  });
});

describe('B1 · the partitions are immutable and disjoint', () => {
  it('developmentCorpus() never yields a blind item', () => {
    expect(dev.length).toBeGreaterThan(0);
    for (const item of dev) expect(item.partition).toBe('development');
  });

  it('blindCorpus() never yields a development item', () => {
    expect(blind.length).toBeGreaterThan(0);
    for (const item of blind) expect(item.partition).toBe('blind');
  });

  it('an item lives under the directory its partition names', () => {
    for (const item of all) expect(item.file.startsWith(`${item.partition}/`)).toBe(true);
  });

  it('no blind item is reachable from the development partition by id or by file', () => {
    const devIds = new Set(dev.map((i) => i.id));
    const devFiles = new Set(dev.map((i) => i.file));
    for (const item of blind) {
      expect(devIds.has(item.id)).toBe(false);
      expect(devFiles.has(item.file)).toBe(false);
    }
  });
});

describe('B1 · labels are well-formed and agree with the field catalogue', () => {
  it('every labelled field is catalogued, and its risk_class is the catalogue answer', () => {
    for (const item of all) {
      for (const label of item.labels) {
        expect(isKnownField(label.field), `${item.id}:${label.field} catalogued`).toBe(true);
        expect(label.risk_class, `${item.id}:${label.field} risk`).toBe(
          riskClassFor(label.field, label.value),
        );
      }
    }
  });

  it('every citation is a real region of a real page (§6.4 normalised geometry)', () => {
    for (const item of all) {
      for (const label of item.labels) {
        expect(label.page, `${item.id}:${label.field} page`).toBeGreaterThanOrEqual(1);
        const [x, y, w, h] = label.bbox;
        for (const n of [x, y, w, h]) expect(Number.isFinite(n)).toBe(true);
        expect(x).toBeGreaterThanOrEqual(0);
        expect(y).toBeGreaterThanOrEqual(0);
        expect(w).toBeGreaterThan(0);
        expect(h).toBeGreaterThan(0);
        expect(x + w, `${item.id}:${label.field} right edge`).toBeLessThanOrEqual(1);
        expect(y + h, `${item.id}:${label.field} bottom edge`).toBeLessThanOrEqual(1);
      }
    }
  });

  it('a field is never both labelled present and declared absent on the same item', () => {
    for (const item of all) {
      const labelled = new Set(item.labels.map((l) => l.field));
      for (const absent of item.absent_fields) {
        expect(labelled.has(absent), `${item.id}: ${absent} cannot be both`).toBe(false);
        expect(isKnownField(absent)).toBe(true);
      }
    }
  });

  it('an item that is not expected to extract carries no labels', () => {
    for (const item of all) {
      if (item.expected_outcome !== 'extracted') expect(item.labels).toEqual([]);
    }
  });
});

describe('B1 · the corpus spec is MET, not merely written down', () => {
  const { minimums } = manifest;

  it('every banded field clears the stated blind support', () => {
    for (const field of manifest.band_fields) {
      const supporting = blind.filter((i) => i.labels.some((l) => l.field === field));
      expect(supporting.length, `blind support for ${field}`).toBeGreaterThanOrEqual(
        minimums.blind_support_per_field,
      );
      const sourceTypes = new Set(supporting.map((i) => i.source_type));
      expect(sourceTypes.size, `source types for ${field}`).toBeGreaterThanOrEqual(
        minimums.source_types_per_field,
      );
    }
  });

  it('every banded field has negative examples — a field genuinely absent', () => {
    for (const field of manifest.band_fields) {
      const negatives = blind.filter((i) => i.absent_fields.includes(field));
      expect(negatives.length, `blind negatives for ${field}`).toBeGreaterThanOrEqual(
        minimums.blind_negatives_per_field,
      );
    }
  });

  it('each partition carries adjudicated ambiguous labels', () => {
    for (const [name, items] of [
      ['development', dev],
      ['blind', blind],
    ] as const) {
      const ambiguous = items.flatMap((i) => i.ambiguous ?? []);
      expect(ambiguous.length, `${name} ambiguous labels`).toBeGreaterThanOrEqual(
        minimums.ambiguous_per_partition,
      );
      for (const a of ambiguous) {
        expect(a.candidates.length).toBeGreaterThanOrEqual(2);
        expect(a.candidates).toContain(a.adjudicated);
        expect(a.rationale.length).toBeGreaterThan(0);
      }
    }
  });

  it('the document classes PRD §6.4 names are all present', () => {
    const classes = new Set(all.map((i) => i.document_class));
    for (const required of [
      'discharge_summary',
      'eob',
      'pill_bottle',
      'handwritten_note',
      'phone_photo_angled',
    ]) {
      expect(classes.has(required), `${required} present`).toBe(true);
    }
  });

  it('the development partition carries the honest-limits fixtures the pipeline must survive', () => {
    const outcomes = new Set(dev.map((i) => i.expected_outcome));
    for (const required of ['needs_password', 'unsupported_type', 'aborted'] as const) {
      expect(outcomes.has(required), `${required} fixture present`).toBe(true);
    }
    // The injection probe is B5's INJ-01 fixture; it EXTRACTS — the whole
    // point is that a fully successful injection still lands as a proposal.
    expect(dev.some((i) => i.document_class === 'injection_probe')).toBe(true);
  });
});
